/* =======================================================
   2. STATE
   Small in-memory object holding whatever the current
   screen needs. Nothing here persists on its own — only
   what we explicitly save to localStorage does.
   ======================================================= */
const state = {
  currentPassage: null,
  timeRemaining: 0,
  timerInterval: null,
  startedAt: null,
  timedOut: false
};

const RING_CIRCUMFERENCE = 213.6; // 2 * PI * r(34), matches the SVG circle in index.html
const HISTORY_KEY = "dokkai_history"; // localStorage key

/* =======================================================
   3. NAVIGATION
   Only one <section class="view"> is visible at a time.
   ======================================================= */
function showView(viewId) {
  document.querySelectorAll(".view").forEach(v => v.classList.remove("active"));
  document.getElementById(viewId).classList.add("active");

  document.querySelectorAll(".nav-btn").forEach(b => b.classList.remove("active"));
  const navBtn = document.querySelector(`.nav-btn[data-view="${viewId}"]`);
  if (navBtn) navBtn.classList.add("active");
}

document.querySelectorAll(".nav-btn").forEach(btn => {
  btn.addEventListener("click", () => {
    const target = btn.dataset.view;
    showView(target);
    if (target === "view-list") renderPassageList();
    if (target === "view-stats") renderStats();
  });
});

/* =======================================================
   4. VIEW 1 — PASSAGE LIST
   ======================================================= */
function renderPassageList() {
  const grid = document.getElementById("passage-list");
  const history = loadHistory();

  grid.innerHTML = "";
  PASSAGES.forEach((p, i) => {
    // find this passage's best past attempt, if any
    const attempts = history.filter(h => h.passageId === p.id);
    const best = attempts.length
      ? attempts.reduce((a, b) => (b.score / b.total > a.score / a.total ? b : a))
      : null;

    const card = document.createElement("div");
    card.className = "passage-card";
    card.innerHTML = `
      <span class="card-num">passage ${String(i + 1).padStart(2, "0")}</span>
      <h3>${p.title}</h3>
      <div class="card-meta">
        <span>${Math.floor(p.timeLimit / 60)}:${String(p.timeLimit % 60).padStart(2, "0")} limit</span>
        <span class="best-badge">${best ? `best: ${best.score}/${best.total}` : "not attempted"}</span>
      </div>
    `;
    card.addEventListener("click", () => startQuiz(p));
    grid.appendChild(card);
  });
}

/* =======================================================
   5. VIEW 2 — QUIZ (passage + timer + questions)
   ======================================================= */
function startQuiz(passage) {
  state.currentPassage = passage;
  state.timeRemaining = passage.timeLimit;
  state.startedAt = Date.now();
  state.timedOut = false;

  document.getElementById("quiz-title").textContent = passage.title;
  document.getElementById("quiz-text").textContent = passage.text;

  const qList = document.getElementById("questions-list");
  qList.innerHTML = "";
  passage.questions.forEach((q, qi) => {
    const block = document.createElement("div");
    block.className = "question-block";
    block.innerHTML = `
      <p class="q-text">Q${qi + 1}. ${q.q}</p>
      ${q.choices.map((choice, ci) => `
        <label class="choice-row">
          <input type="radio" name="q${qi}" value="${ci}">
          <span>${choice}</span>
        </label>
      `).join("")}
    `;
    qList.appendChild(block);
  });

  showView("view-quiz");
  startTimer();
}

function startTimer() {
  clearInterval(state.timerInterval);
  updateTimerDisplay();

  state.timerInterval = setInterval(() => {
    state.timeRemaining--;
    updateTimerDisplay();

    if (state.timeRemaining <= 0) {
      clearInterval(state.timerInterval);
      state.timedOut = true;
      submitQuiz(); // auto-submit whatever was answered so far
    }
  }, 1000);
}

function updateTimerDisplay() {
  const mins = Math.floor(state.timeRemaining / 60);
  const secs = state.timeRemaining % 60;
  document.getElementById("timer-label").textContent = `${mins}:${String(secs).padStart(2, "0")}`;

  // drain the ring proportionally to time left
  const fraction = state.timeRemaining / state.currentPassage.timeLimit;
  const offset = RING_CIRCUMFERENCE * (1 - fraction);
  const ring = document.getElementById("timer-ring-fg");
  ring.style.strokeDashoffset = offset;

  // turn the ring color urgent when under 20% of the time remains
  if (fraction < 0.2) {
    ring.style.stroke = "#d94f3d";
  } else {
    ring.style.stroke = "";
  }
}

document.getElementById("btn-back").addEventListener("click", () => {
  clearInterval(state.timerInterval);
  showView("view-list");
  renderPassageList();
});

document.getElementById("btn-submit").addEventListener("click", submitQuiz);

/* =======================================================
   6. GRADING + RESULTS
   ======================================================= */
function submitQuiz() {
  clearInterval(state.timerInterval);
  const passage = state.currentPassage;
  const timeUsed = passage.timeLimit - state.timeRemaining;

  let score = 0;
  const breakdown = passage.questions.map((q, qi) => {
    const selected = document.querySelector(`input[name="q${qi}"]:checked`);
    const selectedIndex = selected ? parseInt(selected.value, 10) : null;
    const isCorrect = selectedIndex === q.answer;
    if (isCorrect) score++;
    return { question: q.q, isCorrect, chosen: selectedIndex, correctAnswer: q.choices[q.answer] };
  });

  // persist this attempt
  const attempt = {
    passageId: passage.id,
    passageTitle: passage.title,
    score,
    total: passage.questions.length,
    timeUsed,
    timeLimit: passage.timeLimit,
    timedOut: state.timedOut,
    date: new Date().toISOString()
  };
  saveAttempt(attempt);

  renderResults(attempt, breakdown);
  showView("view-results");
}

function renderResults(attempt, breakdown) {
  document.getElementById("results-heading").textContent = attempt.passageTitle;
  document.getElementById("result-score").textContent = `${attempt.score}/${attempt.total}`;

  const mins = Math.floor(attempt.timeUsed / 60);
  const secs = attempt.timeUsed % 60;
  document.getElementById("result-time").textContent = `${mins}:${String(secs).padStart(2, "0")}`;
  document.getElementById("result-status").textContent = attempt.timedOut ? "timed out" : "finished in time";

  const box = document.getElementById("results-breakdown");
  box.innerHTML = breakdown.map((b, i) => `
    <div class="breakdown-row ${b.isCorrect ? "correct" : "incorrect"}">
      <span>Q${i + 1}. ${b.question}</span>
      <span>${b.isCorrect ? "✓ correct" : `✗ correct answer: ${b.correctAnswer}`}</span>
    </div>
  `).join("");
}

document.getElementById("btn-retry").addEventListener("click", () => startQuiz(state.currentPassage));
document.getElementById("btn-to-list").addEventListener("click", () => {
  showView("view-list");
  renderPassageList();
});

/* =======================================================
   7. PERSISTENCE — localStorage
   All attempts are stored as one JSON array under a single
   key. This is the entire "database" for the app.
   ======================================================= */
function loadHistory() {
  try {
    const raw = localStorage.getItem(HISTORY_KEY);
    return raw ? JSON.parse(raw) : [];
  } catch (e) {
    console.error("Could not read history:", e);
    return [];
  }
}

function saveAttempt(attempt) {
  const history = loadHistory();
  history.push(attempt);
  localStorage.setItem(HISTORY_KEY, JSON.stringify(history));
}

/* =======================================================
   8. VIEW 4 — STATS / PROGRESS
   ======================================================= */
function renderStats() {
  const history = loadHistory();
  const summaryEl = document.getElementById("stats-summary");
  const historyEl = document.getElementById("history-list");

  if (history.length === 0) {
    summaryEl.innerHTML = "";
    historyEl.innerHTML = `<div class="empty-state">No attempts yet — complete a passage to start tracking your progress.</div>`;
    return;
  }

  const totalAttempts = history.length;
  const avgAccuracy = Math.round(
    (history.reduce((sum, h) => sum + h.score / h.total, 0) / totalAttempts) * 100
  );
  const avgTime = Math.round(history.reduce((sum, h) => sum + h.timeUsed, 0) / totalAttempts);
  const timeoutRate = Math.round((history.filter(h => h.timedOut).length / totalAttempts) * 100);

  summaryEl.innerHTML = `
    <div class="stat-block">
      <span class="stat-value">${totalAttempts}</span>
      <span class="stat-label">attempts</span>
    </div>
    <div class="stat-block">
      <span class="stat-value">${avgAccuracy}%</span>
      <span class="stat-label">avg accuracy</span>
    </div>
    <div class="stat-block">
      <span class="stat-value">${Math.floor(avgTime / 60)}:${String(avgTime % 60).padStart(2, "0")}</span>
      <span class="stat-label">avg time used</span>
    </div>
    <div class="stat-block">
      <span class="stat-value">${timeoutRate}%</span>
      <span class="stat-label">timed out</span>
    </div>
  `;

  // most recent attempts first
  const sorted = [...history].reverse();
  historyEl.innerHTML = sorted.map(h => {
    const accuracyPct = Math.round((h.score / h.total) * 100);
    const dateStr = new Date(h.date).toLocaleDateString(undefined, { month: "short", day: "numeric" });
    return `
      <div class="history-row">
        <span>${h.passageTitle}</span>
        <span>${dateStr}</span>
        <span>${h.score}/${h.total} ${h.timedOut ? "(timed out)" : ""}</span>
        <span class="bar-cell">
          <span class="history-bar-track">
            <span class="history-bar-fill" style="width:${accuracyPct}%"></span>
          </span>
          ${accuracyPct}%
        </span>
      </div>
    `;
  }).join("");
}

document.getElementById("btn-clear-history").addEventListener("click", () => {
  if (confirm("Clear all saved attempts? This can't be undone.")) {
    localStorage.removeItem(HISTORY_KEY);
    renderStats();
    renderPassageList();
  }
});

